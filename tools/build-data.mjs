// Fetches notable POIs (anything with a wikidata tag) around London from Overpass
// and writes data/pois.js. Area: 43 km radius of Charing Cross (~M25 + 10 miles).
import { writeFileSync } from 'node:fs';
const C = [51.5074, -0.1278], R = 43000;
const a = `(${C[0]-0.39},${C[1]-0.62},${C[0]+0.39},${C[1]+0.62})`; // bbox; trimmed to radius below
const clauses = [
 `nwr[amenity~"^(pub|bar)$"][name]${a};`,
 `nwr[tourism~"^(attraction|museum|gallery|viewpoint|artwork|zoo|theme_park)$"][wikidata]${a};`,
 `nwr[historic][wikidata]${a};`,
 `wr[leisure~"^(park|garden|nature_reserve)$"][name]${a};`,
 `nwr[amenity~"^(theatre|arts_centre|cinema|concert_hall|library|place_of_worship)$"][wikidata]${a};`,
 `nwr[building][wikidata]${a};`,
];
const j = { elements: [] };
for (const c of clauses) {
  for (let i = 0; ; i++) {
    const r = await fetch('https://overpass-api.de/api/interpreter', { method: 'POST', body: 'data=' + encodeURIComponent(`[out:json][timeout:180];(${c});out center tags;`), headers: { 'User-Agent': 'InconvenientRouting/0.1' } });
    if (r.ok) { const d = await r.json(); j.elements.push(...d.elements); console.log(c.slice(0, 30), d.elements.length); break; }
    if (i > 4) throw new Error(r.status + ' on ' + c);
    await new Promise(z => setTimeout(z, 15000));
  }
}
const cat = t => /^(pub|bar)$/.test(t.amenity || '') ? 'pub' : t.leisure ? 'park' : t.tourism === 'museum' || t.tourism === 'gallery' ? 'museum'
  : /theatre|arts_centre|cinema|concert_hall|library/.test(t.amenity || '') ? 'culture'
  : t.tourism === 'viewpoint' ? 'view' : t.historic ? 'historic' : t.amenity === 'place_of_worship' ? 'church' : 'landmark';
// Notability score. Wikidata/Wikipedia links are the baseline; things people actually
// visit get boosted, and buildings that are merely documented (embassies, schools,
// offices, flats) are demoted or dropped (score <= 0).
const DULL_BUILDING = /^(school|office|commercial|residential|apartments|house|industrial|retail|hospital|university|college|government|civic|hotel|warehouse|train_station|transportation|yes)$/;
const DULL_NAME = /(embassy|high commission|consulate|school|academy|college|primary|house of|offices?|headquarters|hq|apartments|court|hall of residence|estate|hospital|surgery|centre for|institute|federation|association|council|bank|insurance|limited|ltd|plc)/i;
function score(t) {
  if (/^(pub|bar)$/.test(t.amenity || '')) return 1 + (t.wikidata ? 2 : 0) + (t.heritage ? 1 : 0);
  let s = (t.wikidata ? 1 : 0) + (t.wikipedia ? 2 : 0);
  if (/^(attraction|museum|gallery|zoo|theme_park|viewpoint)$/.test(t.tourism || '')) s += 4;
  if (t.tourism === 'artwork') s += 1;
  if (/^(castle|palace|monument|fort|ruins|city_gate|archaeological_site|manor|tower)$/.test(t.historic || '')) s += 3;
  else if (t.historic === 'memorial') s += 1;
  if (/^(theatre|arts_centre|concert_hall)$/.test(t.amenity || '')) s += 3;
  if (t.leisure) s += t.wikipedia ? 3 : 1;
  // Impressive architecture is worth walking past whoever's inside (Inns of Court,
  // City livery halls, towers), so it escapes the dull-occupant penalties below.
  const topListed = /^(Grade )?(I|II*)$/i.test(t.listed_status || '');
  const impressive = topListed || !!t.architect || parseFloat(t.height) >= 100 || +t['building:levels'] >= 30;
  if (impressive) s += 2;
  if (topListed || t.heritage === '1') s += 2;
  else if (t.heritage) s += 1;
  if (/^(cathedral|abbey|basilica)$/.test(t.building || '') || /cathedral|abbey|minster/i.test(t.name)) s += 3;
  const attraction = t.tourism || t.historic || t.leisure || /theatre|arts_centre|concert_hall/.test(t.amenity || '');
  if (!attraction && !impressive) {
    if (t.office || t.diplomatic || t.amenity === 'embassy' || /^(school|college|university|kindergarten|hospital|clinic)$/.test(t.amenity || '')) return 0;
    if (DULL_BUILDING.test(t.building || '')) s -= 2;
    if (DULL_NAME.test(t.name)) s -= 3;
    if (/^(cinema|library|place_of_worship)$/.test(t.amenity || '')) s -= 1;
  }
  return s;
}
const seen = new Set(), out = [];
for (const e of j.elements) {
  const t = e.tags || {}, lat = e.lat ?? e.center?.lat, lon = e.lon ?? e.center?.lon;
  if (!t.name || lat == null) continue;
  if (Math.hypot((lat - C[0]) * 111320, (lon - C[1]) * 69400) > R) continue;
  const k = t.name + Math.round(lat * 500) + Math.round(lon * 500);
  if (seen.has(k)) continue; seen.add(k);
  let s = score(t);
  if (s <= 0) continue;
  if (t.leisure && !t.wikidata && e.type === 'node') continue;
  const row = [+lat.toFixed(5), +lon.toFixed(5), t.name, cat(t), s];
  // Wikipedia title ("en:Tower Bridge") or Wikidata id, for thumbnails and descriptions.
  const wiki = t.wikipedia || t.wikidata;
  if (wiki) row.push(wiki);
  out.push(row);
}
writeFileSync(new URL('../data/pois.js', import.meta.url),
  '// Generated by tools/build-data.mjs from OpenStreetMap (ODbL). [lat, lon, name, category, score, wiki?]\nwindow.POIS = ' + JSON.stringify(out) + ';\n');
console.log(out.length, 'POIs');
